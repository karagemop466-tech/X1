def apply(path: str, edits, revert: bool = False) -> int:
    src = open(path, encoding="utf-8").read()
    for old, new in edits:
        want, repl = (new, old) if revert else (old, new)
        n = src.count(want)
        if n != 1:
            print(f"ABORT: anchor occurs {n} times (expected exactly 1) in "
                  f"{os.path.relpath(path, ROOT)}: {want[:70]!r}")
            return 1
        src = src.replace(want, repl, 1)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(src)
    print(f"{'rolled back' if revert else 'applied'}: {len(edits)} edits to {os.path.relpath(path, ROOT)}")
    return 0


def main() -> int:
    argv = sys.argv[1:]
    revert = "--revert" in argv
    only = None
    if "--only" in argv:
        only = [x.strip() for x in argv[argv.index("--only") + 1].split(",")]
    groups = {
        "site-shadow": (TARGET, EDITS, 'SHADOW_SEAL = load_json("shadow/sealed_ledger.json")'),
        "site-next": (TARGET, GROUPS["site-next"], "_NEXT_STEM = sorted("),
        "readiness": (READINESS, GROUPS["readiness"], '"verified_results_2026",'),
    }
    for name in (only or list(groups)):
        path, edits, signature = groups[name]
        src = open(path, encoding="utf-8").read()
        if signature in src and not revert:
            # Anchor counts alone would not catch this: several replacements *contain* their own anchor
            # (they insert around it), so a re-run would duplicate the inserted block rather than abort.
            # The signature is text only this group writes, which makes double application impossible.
            print(f"[{name}] already applied (signature present) — skipping, not re-editing")
            continue
        print(f"[{name}]", end=" ")
        if apply(path, edits, revert):
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
