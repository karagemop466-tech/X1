#!/usr/bin/env python3
"""Build the derived availability report.

Deterministic, auditable join of two hand-transcribed sources:
  data/nfl/injuries_week10.tsv   (official NFL.com Week 10 injury report)
  data/nfl/depth_chart_pilot.tsv (club-published depth charts, 5-club pilot)

Rules enforced here (and printed on the site):
  * A player is labelled "listed starter" ONLY if the club's own depth chart prints
    them in column 1 of their position. Nothing is inferred.
  * If the injured player does not appear on that club's published chart, the
    depth fields are left BLANK and the row is flagged "not listed on club chart".
  * No probability, severity score, or expected-impact number is produced.
    Those would require a licensed historical dataset (see docs/sources/sources.md).
"""
import csv
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INJ = os.path.join(ROOT, "data/nfl/injuries_week10.tsv")
DEPTH = os.path.join(ROOT, "data/nfl/depth_chart_pilot.tsv")
OUT = os.path.join(ROOT, "data/nfl/availability_derived.tsv")


def read_tsv(path):
    rows, header = [], None
    with open(path, newline="", encoding="utf-8") as fh:
        lines = [ln for ln in fh if ln.strip() and not ln.lstrip().startswith("#")]
    reader = csv.DictReader(lines, delimiter="\t")
    header = reader.fieldnames
    for r in reader:
        rows.append(r)
    return header, rows


def norm(name):
    name = name.lower()
    name = name.replace("\u2019", "'").replace("\u2018", "'")
    name = re.sub(r"[.'`]", "", name)
    name = re.sub(r"\s+", " ", name).strip()
    return name


def side_group(pos):
    p = pos.upper()
    if p in {"QB", "RB", "WR", "TE", "FB", "T", "G", "C", "OT", "OG", "OL", "LT", "LG", "RG", "RT"}:
        return "offense"
    if p in {"K", "P", "LS", "H", "PR", "KR"}:
        return "special teams"
    return "defense"


def main():
    _, inj = read_tsv(INJ)
    _, depth = read_tsv(DEPTH)

    # index depth chart: team -> normalized name -> best (lowest) order + raw depth string
    idx = {}
    for d in depth:
        team = d["team"]
        parts = [p.strip() for p in d["depth_order"].split("|")]
        for part in parts:
            m = re.match(r"^(\d+)\.\s*(.+)$", part)
            if not m:
                continue
            order, player = int(m.group(1)), m.group(2).strip()
            key = (team, norm(player))
            cur = idx.get(key)
            if cur is None or order < cur["order"]:
                idx[key] = {
                    "order": order,
                    "total": len(parts),
                    "position": d["position"],
                    "side": d["side"],
                    "raw": d["depth_order"],
                    "url": d["source_url"],
                }

    pilot_teams = sorted({d["team"] for d in depth})
    out_rows = []
    for r in inj:
        team, player = r["team"], r["player"]
        row = dict(r)
        row["depth_position_club"] = ""
        row["depth_rank"] = ""
        row["depth_of"] = ""
        row["listed_starter"] = ""
        row["depth_chart_url"] = ""
        row["depth_status"] = ""
        row["impact_group"] = side_group(r["position"])
        if team not in pilot_teams:
            row["depth_status"] = "not in pilot scope (club chart not collected)"
        else:
            hit = idx.get((team, norm(player)))
            if hit is None:
                row["depth_status"] = "not listed on club depth chart"
            else:
                row["depth_position_club"] = hit["position"]
                row["depth_rank"] = str(hit["order"])
                row["depth_of"] = str(hit["total"])
                row["listed_starter"] = "yes" if hit["order"] == 1 else "no"
                row["depth_chart_url"] = hit["url"]
                row["depth_status"] = "club chart listing"
        out_rows.append(row)

    fields = [
        "game", "team", "player", "position", "injury", "practice_status", "game_status",
        "impact_group", "depth_status", "listed_starter", "depth_rank", "depth_of",
        "depth_position_club", "depth_chart_url", "player_url",
    ]
    with open(OUT, "w", newline="", encoding="utf-8") as fh:
        fh.write("# DERIVED FILE - generated by tools/build_availability.py. Do not hand-edit.\n")
        fh.write("# Inputs: data/nfl/injuries_week10.tsv (official NFL.com) + data/nfl/depth_chart_pilot.tsv (club sites).\n")
        fh.write("# listed_starter=yes means ONLY that the club printed the player in column 1 of a position.\n")
        fh.write("# Blank depth fields = not confirmed. No impact/probability estimate is produced.\n")
        w = csv.DictWriter(fh, fieldnames=fields, delimiter="\t", lineterminator="\n")
        w.writeheader()
        for row in out_rows:
            w.writerow({k: row.get(k, "") for k in fields})

    starters = [r for r in out_rows if r.get("listed_starter") == "yes"]
    two_deep = [r for r in out_rows if r.get("listed_starter") == "no" and r.get("depth_rank") == "2"]
    unlisted = [r for r in out_rows if r["depth_status"] == "not listed on club depth chart"]
    print(f"rows written: {len(out_rows)} -> {os.path.relpath(OUT, ROOT)}")
    print(f"  listed starters with a Week 10 designation : {len(starters)}")
    print(f"  listed 2nd-string (backups) with designation: {len(two_deep)}")
    print(f"  injured players absent from their club chart: {len(unlisted)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
