def badge(level):
    cls = {"HIGH":"b-high","MEDIUM":"b-med","LOW":"b-low","provisional":"b-med","no edge":"b-high"}.get(level,"b-low")
    return f"<span class='badge {cls}'>{html.escape(str(level))}</span>"

def table(headers, rows, cls="", row_classes=None):
    th = "".join(f"<th>{h}</th>" for h in headers)
    trs = ""
    for i, r in enumerate(rows):
        rc = f" class='{row_classes[i]}'" if row_classes and row_classes[i] else ""
        trs += f"<tr{rc}>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>"
    return f"<div class='twrap'><table class='{cls}'><thead><tr>{th}</tr></thead><tbody>{trs}</tbody></table></div>"

