def inline_md(t):
    t = html.escape(t, quote=False)
    t = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2" target="_blank" rel="noopener">\1</a>', t)
    t = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", t)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    return t

def md_to_html(md):
    out, lines = [], md.splitlines()
    i = 0
    while i < len(lines):
        ln = lines[i]
        s = ln.strip()
        if not s: i += 1; continue
        if s.startswith("<"):        # raw HTML block (generated tables) — pass through verbatim
            out.append(ln); i += 1; continue
        if s.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            if len(rows) >= 2 and all(set("".join(r)) <= set("-: ") for r in rows[1]):
                hdr, body = rows[0], rows[2:]
            else:
                hdr, body = rows[0], rows[1:]
            out.append("<div class='twrap'><table><thead><tr>" + "".join(f"<th>{inline_md(c)}</th>" for c in hdr) +
                       "</tr></thead><tbody>" +
                       "".join("<tr>" + "".join(f"<td>{inline_md(c)}</td>" for c in r) + "</tr>" for r in body) +
                       "</tbody></table></div>")
            continue
        if s.startswith("#"):
            lvl = len(s) - len(s.lstrip("#"))
            out.append(f"<h{lvl}>{inline_md(s.lstrip('#'))}</h{lvl}>")
            i += 1; continue
        if s == "---":
            out.append("<hr>"); i += 1; continue
        if s.startswith("- "):
            items = []
            while i < len(lines) and lines[i].strip().startswith("- "):
                items.append(lines[i].strip()[2:]); i += 1
            out.append("<ul>" + "".join(f"<li>{inline_md(it)}</li>" for it in items) + "</ul>")
            continue
        para = [s]; i += 1
        while i < len(lines) and lines[i].strip() and not lines[i].strip().startswith(("#","|","- ","---")):
            para.append(lines[i].strip()); i += 1
        out.append("<p>" + inline_md(" ".join(para)) + "</p>")
    return "\n".join(out)

